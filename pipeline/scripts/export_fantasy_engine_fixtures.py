"""Export test fixtures for the TypeScript fantasy engine (site/src/lib/fantasy/engine).

Writes two JSON files into site/src/lib/fantasy/engine/__fixtures__/:

- scoring_parity.json: real recorded weekends (2026 oracle inputs, 2025 Wayback driver
  inputs) as plain scoring inputs, with the Python reference result (f1p.fantasy.scoring)
  and the official total, so the TS port can be checked for exact parity.
- history.json: per season (2025, 2026), per round, per asset: price going into the round,
  official points and price after the round. Used by the engine backtest.

Run: cd pipeline && uv run python scripts/export_fantasy_engine_fixtures.py
"""

import json
from pathlib import Path

import pandas as pd

from f1p.fantasy import scoring
from f1p.fantasy import validate as v
from f1p.paths import ROOT_DIR

OUT_DIR = ROOT_DIR / "site" / "src" / "lib" / "fantasy" / "engine" / "__fixtures__"
HISTORY_SEASONS = (2025, 2026)


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    parity = {
        "note": "Generated by pipeline/scripts/export_fantasy_engine_fixtures.py from real recorded weekends.",
        "cases": [*parity_cases(2026, "oracle"), *parity_cases(2025, "wayback")],
    }
    write(OUT_DIR / "scoring_parity.json", parity)
    history = {
        "note": "Generated by pipeline/scripts/export_fantasy_engine_fixtures.py from fantasy_prices/fantasy_points.",
        "seasons": {str(season): history_rows(season) for season in HISTORY_SEASONS},
    }
    write(OUT_DIR / "history.json", history)
    case_count = len(parity["cases"])
    print("cases", case_count)


def parity_cases(season: int, mode: str) -> list[dict]:
    points = v._table("fantasy_points")
    points = points[points["season"] == season]
    if mode == "oracle":
        official = points[points["breakdownSource"].notna()]
    else:
        official = points[(points["kind"] == "driver") & points["wb_overtakes"].notna()]
    inputs = v._results_inputs(season)
    rules = scoring.rules_for(season)
    weekends: dict = {}
    cases = []
    for row in official[official["kind"] == "driver"].itertuples():
        weekend = v._driver_weekend(row, inputs, {}, mode)
        if weekend is None:
            continue
        weekends[(row.round, row.driverId)] = weekend
        result = scoring.score_driver(weekend, rules)
        inputs_json = weekend_json(weekend)
        python_json = points_json(result)
        cases.append({
            "season": season, "round": int(row.round), "kind": "driver", "id": row.driverId,
            "weekend": inputs_json,
            "python": python_json,
            "officialTotal": float(row.points),
        })
    if mode != "oracle":
        return cases
    for row in official[official["kind"] == "constructor"].itertuples():
        team = v._constructor_inputs(row, inputs, {}, weekends, mode)
        if team is None:
            continue
        drivers, _ = team
        field = inputs[row.round]["field"]
        result = scoring.score_constructor(drivers, rules, field_size=field)
        pit = official_pit_points(row)
        driver_inputs = [weekend_json(d) for d in drivers]
        python_json = points_json(result)
        cases.append({
            "season": season, "round": int(row.round), "kind": "constructor",
            "id": row.constructorId, "fieldSize": int(field),
            "drivers": driver_inputs,
            "officialPitPoints": pit,
            "python": python_json,
            "officialTotal": float(row.points),
        })
    return cases


def history_rows(season: int) -> list[dict]:
    prices = v._table("fantasy_prices")
    points = v._table("fantasy_points")
    prices = prices[prices["season"] == season]
    points = points[points["season"] == season]
    keys = ["season", "round", "kind", "fantasyId", "fantasyCode", "fantasyName"]
    merged = prices.merge(points[[*keys, "points"]], on=keys, how="left")
    rows = []
    ordered = merged.sort_values(["round", "kind", "fantasyId"])
    for row in ordered.itertuples():
        asset_id = row.driverId if row.kind == "driver" else row.constructorId
        rows.append({
            "round": int(row.round), "kind": row.kind, "id": asset_id,
            "fantasyId": str(row.fantasyId), "name": row.fantasyName,
            "constructorId": row.constructorId, "active": bool(row.active),
            "price": float(row.price),
            "priceAfter": optional_float(row.priceAfter),
            "points": optional_float(row.points),
        })
    return rows


def official_pit_points(row) -> float:
    total = 0.0
    for column in ("pit_band", "pit_fastest", "pit_world_record"):
        value = getattr(row, column)
        if pd.notna(value):
            total += float(value)
    return total


def optional_float(value):
    if pd.isna(value):
        return None
    return float(value)


def weekend_json(weekend: scoring.DriverWeekend) -> dict:
    return {
        "qualiPosition": weekend.quali_position,
        "qualiDisqualified": weekend.quali_disqualified,
        "qualiSegment": weekend.quali_segment,
        "sprint": session_json(weekend.sprint),
        "race": session_json(weekend.race),
    }


def session_json(session: scoring.SessionResult | None) -> dict | None:
    if session is None:
        return None
    return {
        "grid": None if session.grid is None else int(session.grid),
        "finish": None if session.finish is None else int(session.finish),
        "classified": bool(session.classified),
        "disqualified": bool(session.disqualified),
        "fastestLap": bool(session.fastest_lap),
        "overtakes": None if session.overtakes is None else int(session.overtakes),
        "driverOfTheDay": bool(session.driver_of_the_day),
    }


def points_json(points) -> dict:
    breakdown = {key: int(value) for key, value in points.breakdown.items()}
    return {"qualifying": int(points.qualifying), "sprint": int(points.sprint),
            "race": int(points.race), "total": int(points.total), "breakdown": breakdown}


def write(path: Path, payload: dict) -> None:
    text = json.dumps(payload, separators=(",", ":"))
    path.write_text(text, encoding="utf-8")
    size_kb = len(text) // 1024
    print("wrote", path, size_kb, "KB")


if __name__ == "__main__":
    main()
